#!/usr/bin/env node
// Stamps the standard TNQ boot block (SPEC-OFFLINE.md) into every module registered
// in index.html's LESSONS_REGISTRY, normalises font stacks and removes zoom locks.
//   node tools/apply-boot.mjs          -> rewrite files in place
//   node tools/apply-boot.mjs --check  -> exit 1 if any file is out of date (CI / tests)
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

export const LIBS = {
  tailwind: { global: 'tailwind', local: 'lib/tailwind.js', cdn: 'https://cdn.tailwindcss.com' },
  tone: { global: 'Tone', local: 'lib/Tone.js', cdn: 'https://cdnjs.cloudflare.com/ajax/libs/tone/14.8.49/Tone.js' },
  confetti: { global: 'confetti', local: 'lib/confetti.browser.min.js', cdn: 'https://cdn.jsdelivr.net/npm/canvas-confetti@1.6.0/dist/confetti.browser.min.js' },
};

// Native fallback matrix (SPEC-OFFLINE.md §4). Order matters: brand font first, then
// the OS-native equivalents, then the generic family.
export const FONT_MATRIX = {
  'sans-serif': ["'Segoe UI'", "'SF Pro Rounded'", "'SF Pro Text'", '-apple-system', 'BlinkMacSystemFont', 'system-ui', 'Roboto', "'Helvetica Neue'", 'Arial'],
  cursive: ["'Chalkboard SE'", 'Chalkboard', "'Comic Sans MS'", "'Segoe Print'", "'Marker Felt'"],
  monospace: ["'SF Mono'", "'Cascadia Mono'", 'Consolas', 'Menlo', "'Courier New'"],
};

export function readRegistry() {
  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const m = html.match(/const LESSONS_REGISTRY\s*=\s*(\[[\s\S]*?\n\s*\]);/);
  if (!m) throw new Error('LESSONS_REGISTRY not found in index.html');
  return vm.runInNewContext(m[1]);
}

const BOOT_RE = /[ \t]*<!-- TNQ:BOOT:BEGIN[\s\S]*?<!-- TNQ:BOOT:END -->\r?\n?/;
const libScriptRe = (lib) => {
  const names = [lib.local, lib.cdn].map((s) => s.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')).join('|');
  return new RegExp(`[ \\t]*<script[^>]*src="(?:${names}|[^"]*${path.basename(lib.local).replace(/\./g, '\\.')})"[^>]*>\\s*</script>\\r?\\n?`, 'g');
};

function normaliseFontList(list) {
  const parts = list.split(',').map((s) => s.trim()).filter(Boolean);
  const generic = ['sans-serif', 'cursive', 'monospace', 'serif'].find((g) => parts.at(-1) === g) || 'sans-serif';
  const key = (s) => s.replace(/['"]/g, '').toLowerCase();
  const named = parts.filter((p) => !['sans-serif', 'cursive', 'monospace', 'serif'].includes(p));
  const out = [];
  for (const f of [...named, ...(FONT_MATRIX[generic] || FONT_MATRIX['sans-serif']), generic]) {
    if (!out.some((o) => key(o) === key(f))) out.push(f.replace(/"/g, "'"));
  }
  return out.join(', ');
}

export function patchFonts(html) {
  // Only touch CSS inside <style> blocks, never JS strings.
  return html.replace(/(<style[^>]*>)([\s\S]*?)(<\/style>)/g, (all, a, css, b) =>
    a + css.replace(/font-family:\s*([^;{}]+);/g, (decl, list) =>
      `font-family: ${normaliseFontList(list)};`) + b);   // idempotent: re-normalising is a no-op
}

export function buildBlock({ libs, fonts, moduleId, runtime }) {
  const lines = [
    '  <!-- TNQ:BOOT:BEGIN generated by tools/apply-boot.mjs from tools/tnq-boot.js - edit those, then run: npm run boot -->',
  ];
  if (libs.length) {
    lines.push(`  <script>window.TNQB={s:{},n:function(k,g,u){if(window[g]){this.s[k]='local'}else{this.s[k]='cdn';document.write('<script src="'+u+'"><\\/script>')}}}</script>`);
    for (const k of libs) {
      const L = LIBS[k];
      lines.push(`  <script src="${L.local}"></script>`);
      lines.push(`  <script>TNQB.n('${k}','${L.global}','${L.cdn}')</script>`);
    }
  }
  const fontAttr = fonts ? ` data-tnq-fonts="${fonts.replace(/&amp;/g, '&').replace(/&/g, '&amp;')}"` : '';
  lines.push(`  <script data-tnq-module="${moduleId}"${fontAttr}>\n${runtime.trim()}\n  </script>`);
  lines.push('  <!-- TNQ:BOOT:END -->');
  return lines.join('\n') + '\n';
}

export function transform(html, file) {
  const runtime = fs.readFileSync(path.join(ROOT, 'tools', 'tnq-boot.js'), 'utf8');
  if (/<\/script/i.test(runtime)) throw new Error('tools/tnq-boot.js must not contain a closing script tag');
  let out = html.replace(BOOT_RE, '');
  // Detect needs from the code that remains (or from the previous boot block).
  const libs = [];
  if (/lib\/tailwind\.js|cdn\.tailwindcss\.com/.test(html)) libs.push('tailwind');
  if (/\bTone\.[A-Za-z]/.test(out)) libs.push('tone');
  if (/\bconfetti\s*\(/.test(out)) libs.push('confetti');
  for (const L of Object.values(LIBS)) out = out.replace(libScriptRe(L), '');

  let fonts = (html.match(/data-tnq-fonts="([^"]+)"/) || [])[1] || null;
  const linkRe = /[ \t]*<link\b[^>]*href="(https:\/\/fonts\.googleapis\.com\/css2[^"]*)"[^>]*>\r?\n?/;
  const lm = out.match(linkRe);
  if (lm) { fonts = lm[1]; out = out.replace(linkRe, ''); }  out = out.replace(/[ \t]*<link\b[^>]*rel="preconnect"[^>]*fonts\.(?:googleapis|gstatic)\.com[^>]*>\r?\n?/g, '');
  out = out.replace(/[ \t]*<!--\s*(Tailwind CSS CDN|Tone\.js[^>]*|Canvas Confetti|Google Fonts[^>]*)\s*-->\r?\n?/g, '');

  // WCAG 1.4.4: never block pinch-zoom.
  out = out.replace(/,\s*maximum-scale=[\d.]+/g, '').replace(/,\s*user-scalable=(no|0)/g, '');
  out = patchFonts(out);

  const block = buildBlock({ libs, fonts, moduleId: path.basename(file, '.html'), runtime });
  if (!/<\/title>\r?\n/.test(out)) throw new Error(`${file}: no <title> to anchor the boot block`);
  out = out.replace(/(<\/title>\r?\n)/, `$1${block}`);
  return { out, libs, fonts: !!fonts };
}

// Service worker: precache list + content-hash version, so any edit ships a new cache.
export function buildServiceWorker(outputs) {
  const libs = [...new Set(Object.values(outputs).flatMap((o) => o.libs))].map((k) => LIBS[k].local);
  const icons = fs.readdirSync(path.join(ROOT, 'icons')).filter((f) => /\.(png|svg)$/.test(f)).sort().map((f) => `icons/${f}`);
  const pages = ['index.html', ...Object.keys(outputs)];
  const precache = ['./', ...pages, 'manifest.webmanifest', ...icons, ...libs];
  const hash = crypto.createHash('sha256');
  for (const f of precache.slice(1)) hash.update(f).update(outputs[f]?.out ?? fs.readFileSync(path.join(ROOT, f)));
  const tpl = fs.readFileSync(path.join(ROOT, 'tools', 'sw-template.js'), 'utf8');
  return tpl.replace('__VERSION__', hash.digest('hex').slice(0, 12)).replace('__PRECACHE__', JSON.stringify(precache, null, 2));
}

function main() {
  const files = readRegistry().flatMap((g) => g.items.map((i) => i.file));
  let stale = 0;
  const outputs = {};
  for (const f of files) {
    const p = path.join(ROOT, f);
    const src = fs.readFileSync(p, 'utf8');
    const { out, libs, fonts } = transform(src, f);
    outputs[f] = { out, libs };
    const changed = out !== src;
    if (changed) stale++;
    if (!CHECK && changed) fs.writeFileSync(p, out);
    console.log(`${changed ? (CHECK ? 'STALE ' : 'wrote ') : 'ok    '} ${f.padEnd(46)} libs=[${libs.join(',')}] webfonts=${fonts}`);
  }
  const swPath = path.join(ROOT, 'sw.js');
  const sw = buildServiceWorker(outputs);
  const swOld = fs.existsSync(swPath) ? fs.readFileSync(swPath, 'utf8') : '';
  if (sw !== swOld) { stale++; if (!CHECK) fs.writeFileSync(swPath, sw); }
  console.log(`${sw === swOld ? 'ok    ' : CHECK ? 'STALE ' : 'wrote '} sw.js (${sw.match(/tnq-([0-9a-f]+)/)[1]})`);
  if (CHECK && stale) { console.error(`\n${stale} module(s) out of date. Run: npm run boot`); process.exit(1); }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
